"""
Draws the website's DermEdge logo (the drop in web/index.html's header SVG) as anti-aliased
4-bit masks for the band's screen:  python3 tools/make_art.py  -> main/art.c, main/art.h

The SVG, on a 40x40 grid:
  circle  cx=20 cy=20 r=19                                    (pale teal)
  drop    M20 8 c5 7 9 11.5 9 16.5 a9 9 0 0 1-18 0 C11 19.5 15 15 20 8z   (teal)
  shine   M16 25.5 a4.5 4.5 0 0 0 4.5 4, stroke 2, round caps            (white)
Each layer is its own mask, so the band can colour them. Sizes: the header, the home screen
and the boot screen.
"""
import math
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SIZES = {"logo_sm": 14, "logo_md": 30, "logo_lg": 56}
SS = 16  # supersampling


def cubic(p0, p1, p2, p3, n=40):
    return [tuple((1 - t) ** 3 * a + 3 * (1 - t) ** 2 * t * b + 3 * (1 - t) * t ** 2 * c + t ** 3 * d
                  for a, b, c, d in zip(p0, p1, p2, p3)) for t in (i / n for i in range(n + 1))]


def arc(p0, p1, r, sweep, n=40):
    """SVG arc (small arc) from p0 to p1; sweep 1 = increasing angle (clockwise on screen)."""
    (x0, y0), (x1, y1) = p0, p1
    mx, my, dx, dy = (x0 + x1) / 2, (y0 + y1) / 2, x1 - x0, y1 - y0
    half = math.hypot(dx, dy) / 2
    h = math.sqrt(max(r * r - half * half, 0))
    for sign in (1, -1):
        cx, cy = mx - sign * dy / (2 * half) * h, my + sign * dx / (2 * half) * h
        a0, a1 = math.atan2(y0 - cy, x0 - cx), math.atan2(y1 - cy, x1 - cx)
        da = (a1 - a0) % (2 * math.pi) if sweep else -((a0 - a1) % (2 * math.pi))
        if abs(da) <= math.pi + 1e-6:  # the small arc in the sweep direction
            return [(cx + r * math.cos(a0 + da * i / n), cy + r * math.sin(a0 + da * i / n)) for i in range(n + 1)]
    raise ValueError("no arc")


def layers():
    drop = cubic((20, 8), (25, 15), (29, 19.5), (29, 24.5)) + arc((29, 24.5), (11, 24.5), 9, 1)[1:] + \
        cubic((11, 24.5), (11, 19.5), (15, 15), (20, 8))[1:]
    shine = arc((16, 25.5), (20.5, 29.5), 4.5, 0)
    return drop, shine


def render(size):
    big = size * SS
    k = big / 40
    drop, shine = layers()
    out = {}
    for name in ("circle", "drop", "shine"):
        img = Image.new("L", (big, big), 0)
        d = ImageDraw.Draw(img)
        if name == "circle":
            d.ellipse([(20 - 19) * k, (20 - 19) * k, (20 + 19) * k, (20 + 19) * k], fill=255)
        elif name == "drop":
            d.polygon([(x * k, y * k) for x, y in drop], fill=255)
        else:
            w = 2 * k
            pts = [(x * k, y * k) for x, y in shine]
            d.line(pts, fill=255, width=round(w), joint="curve")
            for x, y in (pts[0], pts[-1]):  # round caps
                d.ellipse([x - w / 2, y - w / 2, x + w / 2, y + w / 2], fill=255)
        out[name] = img.resize((size, size), Image.LANCZOS)
    return out


def pack(img):
    px = [round(v * 15 / 255) for v in img.getdata()]
    if len(px) % 2:
        px.append(0)
    return bytes(px[i] << 4 | px[i + 1] for i in range(0, len(px), 2))


def main():
    c = ["// Generated by tools/make_art.py from the website's logo (web/index.html). Do not edit.",
         '#include "art.h"', ""]
    h = ["// Generated by tools/make_art.py. The DermEdge logo as anti-aliased 4-bit masks, one per",
         "// layer (pale circle, teal drop, white shine), at three sizes.", "#pragma once",
         "#include <stdint.h>", "", "typedef struct {", "    const uint8_t *bits;  // two 4-bit pixels a byte, rows left to right",
         "    uint8_t w, h;", "} mask_t;", ""]
    previews = []
    for name, size in SIZES.items():
        ls = render(size)
        for layer, img in ls.items():
            sym = f"{name}_{layer}"
            data = pack(img)
            rows = ",\n".join("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 20]) for i in range(0, len(data), 20))
            c += [f"static const uint8_t {sym}_bits[] = {{\n{rows}\n}};",
                  f"const mask_t {sym} = {{{sym}_bits, {size}, {size}}};", ""]
            h.append(f"extern const mask_t {sym};")
        # a colour preview, website colours, to check the drawing by eye
        p = Image.new("RGB", (size, size), (255, 255, 255))
        for layer, col in (("circle", (220, 239, 236)), ("drop", (15, 124, 116)), ("shine", (255, 255, 255))):
            p.paste(Image.new("RGB", (size, size), col), (0, 0), ls[layer])
        previews.append(p.resize((size * 4, size * 4), Image.NEAREST))
    (ROOT / "main/art.c").write_text("\n".join(c) + "\n")
    (ROOT / "main/art.h").write_text("\n".join(h) + "\n")
    sheet = Image.new("RGB", (sum(p.width for p in previews) + 20 * len(previews), max(p.height for p in previews)), "white")
    x = 0
    for p in previews:
        sheet.paste(p, (x, 0))
        x += p.width + 20
    sheet.save(ROOT / "tools/art_preview.png")
    print("wrote main/art.c, main/art.h, tools/art_preview.png")


if __name__ == "__main__":
    main()
