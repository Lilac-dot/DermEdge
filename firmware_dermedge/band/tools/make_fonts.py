"""
Turns the website's fonts (Young Serif and Figtree, web/static/fonts, SIL Open Font License 1.1)
into 4-bit anti-aliased bitmap fonts for the band's ST7735:  python3 tools/make_fonts.py

Writes main/fonts.c and main/fonts.h. Each glyph is stored tight to its ink, two pixels a byte
(16 levels of coverage), with its offset from the pen position, so display.c can blend it onto
whatever is underneath.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
WEB_FONTS = ROOT.parents[1] / "web" / "static" / "fonts"
SERIF = WEB_FONTS / "YoungSerif-400.woff2"
SANS = WEB_FONTS / "Figtree-variable.woff2"
CHARS = [chr(c) for c in range(32, 127)]

# name, file, pixel size, Figtree weight (None for the serif), what it's for
FONTS = [
    ("font_title", SERIF, 18, None, "screen titles"),
    ("font_big", SERIF, 28, None, "the timer and the pairing code"),
    ("font_body", SANS, 11, 500, "body text"),
    ("font_label", SANS, 10, 600, "small labels and the header"),
]


def render(path, size, weight):
    f = ImageFont.truetype(str(path), size)
    if weight:
        f.set_variation_by_axes([weight])
    ascent, descent = f.getmetrics()
    glyphs, bits = [], bytearray()
    for ch in CHARS:
        adv = round(f.getlength(ch))
        l, t, r, b = f.getbbox(ch, anchor="ls")  # relative to the pen on the baseline
        w, h = max(r - l, 0), max(b - t, 0)
        offset = len(bits)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=f, fill=255, anchor="ls")
            px = [round(v * 15 / 255) for v in img.getdata()]
            if len(px) % 2:
                px.append(0)
            bits += bytes(px[i] << 4 | px[i + 1] for i in range(0, len(px), 2))
        glyphs.append((offset, w, h, l, t, adv))
    return dict(ascent=ascent, descent=descent, glyphs=glyphs, bits=bits)


def c_bytes(data, indent="    ", per_line=20):
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + per_line]) for i in range(0, len(data), per_line)]
    return ",\n".join(indent + r for r in rows)


def main():
    out_c = ['// Generated by tools/make_fonts.py from the website\'s Young Serif and Figtree',
             '// (SIL Open Font License 1.1). Do not edit; rerun the script.',
             '#include "fonts.h"', '']
    out_h = ['// Generated by tools/make_fonts.py. Anti-aliased bitmap fonts from the website\'s',
             '// Young Serif and Figtree (SIL Open Font License 1.1), printable ASCII only.',
             '#pragma once', '#include <stdint.h>', '',
             'typedef struct {',
             '    uint32_t offset;   // into the font\'s bits, two 4-bit pixels a byte, rows left to right',
             '    uint8_t w, h;',
             '    int8_t x, y;       // top-left of the ink from the pen on the baseline (y is negative: up)',
             '    uint8_t advance;',
             '} glyph_t;', '',
             'typedef struct {',
             '    const uint8_t *bits;',
             '    const glyph_t *glyphs;  // characters 32..126',
             '    uint8_t ascent, descent;',
             '} font_t;', '']
    total = 0
    for name, path, size, weight, use in FONTS:
        r = render(path, size, weight)
        total += len(r["bits"])
        out_c.append(f'static const uint8_t {name}_bits[] = {{\n{c_bytes(r["bits"])}\n}};')
        rows = ",\n".join(f"    {{{o}, {w}, {h}, {x}, {y}, {a}}}" for o, w, h, x, y, a in r["glyphs"])
        out_c.append(f'static const glyph_t {name}_glyphs[] = {{\n{rows}\n}};')
        out_c.append(f'const font_t {name} = {{{name}_bits, {name}_glyphs, {r["ascent"]}, {r["descent"]}}};\n')
        label = f"{path.stem.split('-')[0]} {size}px" + (f" weight {weight}" if weight else "")
        out_h.append(f'extern const font_t {name};  // {label}: {use}')
        print(f"{name}: {label}, {len(r['bits'])} bytes")
    (ROOT / "main" / "fonts.c").write_text("\n".join(out_c) + "\n")
    (ROOT / "main" / "fonts.h").write_text("\n".join(out_h) + "\n")
    print(f"total {total} bytes of glyphs")


if __name__ == "__main__":
    main()
